"""版本和构建信息"""

from __future__ import annotations

import hashlib
import json
import subprocess
from dataclasses import dataclass
from pathlib import Path

from ._version import __version__

# Runtime dirs/files the services actually write. Not configurable.
PACKAGE_INTEGRITY_RUNTIME_EXCLUSIONS = frozenset(
    {
        "runs",
        "logs",
        "run",
        "data/raw",
        "data/datasets",
        "data/klines",
        "ledger.db",
    }
)
PACKAGE_MANIFEST_NAME = "PACKAGE_MANIFEST"
BUILD_INFO_REL = "src/htx_trend/research/_build_info.py"
_PACKAGE_CONTENT_HASH_PREFIX = "PACKAGE_CONTENT_HASH"


@dataclass
class VersionInfo:
    version: str
    commit: str
    branch: str
    dirty: bool
    
    def to_dict(self) -> dict:
        return {
            "version": self.version,
            "commit": self.commit,
            "branch": self.branch,
            "dirty": self.dirty,
        }
    
    def __str__(self) -> str:
        suffix = "-dirty" if self.dirty else ""
        return f"{self.version} ({self.branch}@{self.commit[:8]}{suffix})"


def write_build_info(
    path: Path,
    version: str,
    git_info: dict,
    strategy_manifest_sha256: str = "",
    package_content_hash: str = "",
) -> None:
    """Write a generated _build_info.py for git-archive / packaged deploys.

    PACKAGE_CONTENT_HASH is the PACKAGE_MANIFEST ``content_hash`` (hash of the
    files mapping). The listed SHA256 of this file in PACKAGE_MANIFEST excludes
    the PACKAGE_CONTENT_HASH line so the cycle can close after the hash is
    written.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "# Generated by scripts/package.py — do not edit by hand.\n"
        "# PACKAGE_MANIFEST lists this file hashed without the PACKAGE_CONTENT_HASH line.\n"
        f"COMMIT = {git_info['commit']!r}\n"
        f"BRANCH = {git_info['branch']!r}\n"
        f"VERSION = {version!r}\n"
        f"DIRTY = {bool(git_info.get('dirty'))}\n"
        f"STRATEGY_MANIFEST_SHA256 = {strategy_manifest_sha256!r}\n"
        f"PACKAGE_CONTENT_HASH = {package_content_hash!r}\n"
    )


def _load_build_info() -> dict:
    try:
        from . import _build_info
    except ImportError:
        return {}
    commit = getattr(_build_info, "COMMIT", "") or ""
    if not commit or commit == "unknown":
        return {}
    return {
        "commit": commit,
        "branch": getattr(_build_info, "BRANCH", "") or "unknown",
        "version": getattr(_build_info, "VERSION", "") or "",
        "dirty": bool(getattr(_build_info, "DIRTY", False)),
        "package_content_hash": getattr(_build_info, "PACKAGE_CONTENT_HASH", "") or "",
    }


def get_git_info() -> tuple[str, str, bool]:
    """获取 git 信息：(commit, branch, dirty)"""
    try:
        repo_root = Path(__file__).parent.parent.parent.parent
        
        commit = subprocess.run(
            ["git", "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
            cwd=repo_root,
        ).stdout.strip()
        
        branch = subprocess.run(
            ["git", "rev-parse", "--abbrev-ref", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
            cwd=repo_root,
        ).stdout.strip()
        
        status = subprocess.run(
            ["git", "status", "--porcelain"],
            capture_output=True,
            text=True,
            check=True,
            cwd=repo_root,
        ).stdout.strip()
        
        dirty = len(status) > 0
        
        return commit, branch, dirty
    
    except Exception:
        return "unknown", "unknown", False


def package_root() -> Path:
    return Path(__file__).resolve().parents[3]


def load_package_manifest(root: Path | None = None) -> dict:
    """Read PACKAGE_MANIFEST written by scripts/package.py (per-file + content hash)."""
    base = root or package_root()
    path = base / "PACKAGE_MANIFEST"
    if not path.is_file():
        return {}
    payload = json.loads(path.read_text())
    return payload if isinstance(payload, dict) else {}


def _file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _build_info_bytes_without_content_hash(data: bytes) -> bytes:
    text = data.decode()
    kept = [
        line
        for line in text.splitlines(keepends=True)
        if not line.startswith(_PACKAGE_CONTENT_HASH_PREFIX)
    ]
    return "".join(kept).encode()


def file_sha256_for_manifest(path: Path, rel: str | None = None) -> str:
    """SHA256 used in PACKAGE_MANIFEST. ``_build_info.py`` excludes the hash line."""
    key = (rel or path.name).replace("\\", "/")
    data = path.read_bytes()
    if key == BUILD_INFO_REL or path.name == "_build_info.py":
        data = _build_info_bytes_without_content_hash(data)
    return hashlib.sha256(data).hexdigest()


def package_content_hash_from_files(files: dict) -> str:
    blob = json.dumps(files, sort_keys=True, separators=(",", ":")).encode()
    return hashlib.sha256(blob).hexdigest()


def _expected_sha(value: object) -> str:
    if isinstance(value, dict):
        text = str(value.get("sha256") or "")
    else:
        text = str(value or "")
    return text.removeprefix("sha256:")


def _is_integrity_excluded(rel: str) -> bool:
    parts = Path(rel).parts
    if "__pycache__" in parts:
        return True
    if rel.endswith(".pyc") or rel.endswith(".pyo"):
        return True
    if rel == PACKAGE_MANIFEST_NAME:
        return True
    for excluded in PACKAGE_INTEGRITY_RUNTIME_EXCLUSIONS:
        if rel == excluded or rel.startswith(f"{excluded}/"):
            return True
    return False


def _iter_package_tree_files(root: Path) -> list[str]:
    found: list[str] = []
    for path in root.rglob("*"):
        if not path.is_file():
            continue
        rel = path.relative_to(root).as_posix()
        if _is_integrity_excluded(rel):
            continue
        found.append(rel)
    return found


def _parse_build_info_file(path: Path) -> dict:
    namespace: dict = {}
    exec(path.read_text(), namespace)
    commit = namespace.get("COMMIT") or ""
    return {
        "commit": commit,
        "branch": namespace.get("BRANCH") or "unknown",
        "version": namespace.get("VERSION") or "",
        "dirty": bool(namespace.get("DIRTY", False)),
        "package_content_hash": namespace.get("PACKAGE_CONTENT_HASH") or "",
    }


def load_build_info_from_root(root: Path) -> dict:
    candidates = (
        root / BUILD_INFO_REL,
        root / "_build_info.py",
    )
    for path in candidates:
        if path.is_file():
            return _parse_build_info_file(path)
    return _load_build_info()


def is_packaged_build_info(info: dict) -> bool:
    commit = str(info.get("commit") or "")
    if commit and commit != "unknown":
        return True
    return bool(info.get("package_content_hash"))


def verify_package_files(root: Path | None = None, manifest: dict | None = None) -> str:
    base = root or package_root()
    payload = manifest if manifest is not None else load_package_manifest(base)
    files = payload.get("files") if isinstance(payload, dict) else None
    if not files:
        raise ValueError("PACKAGE_MANIFEST is present but lists no files")
    mismatches: list[str] = []
    for rel, expected in files.items():
        path = base / str(rel)
        if not path.is_file():
            mismatches.append(f"{rel}: missing")
            continue
        actual = file_sha256_for_manifest(path, str(rel))
        want = _expected_sha(expected)
        if actual != want:
            mismatches.append(f"{rel}: sha256 mismatch")
    listed = {str(rel) for rel in files}
    for rel in _iter_package_tree_files(base):
        if rel not in listed:
            mismatches.append(f"{rel}: unexpected file")
    if mismatches:
        raise ValueError(
            "PACKAGE_MANIFEST verification failed:\n" + "\n".join(mismatches)
        )
    recomputed = package_content_hash_from_files(
        {str(rel): _expected_sha(expected) for rel, expected in files.items()}
    )
    listed_hash = str(payload.get("content_hash") or "")
    if listed_hash and listed_hash != recomputed:
        raise ValueError(
            "PACKAGE_MANIFEST content_hash does not match the files mapping"
        )
    return recomputed


def _git_run(root: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", *args],
        capture_output=True,
        text=True,
        cwd=root,
    )


def _git_porcelain(root: Path) -> str:
    status = _git_run(root, "status", "--porcelain")
    if status.returncode != 0:
        raise ValueError(
            "git status failed; refuse non-SMOKE run without PACKAGE_MANIFEST. "
            + (status.stderr or status.stdout)
        )
    return status.stdout


def _git_toplevel(root: Path) -> Path | None:
    result = _git_run(root, "rev-parse", "--show-toplevel")
    if result.returncode != 0:
        return None
    text = result.stdout.strip()
    if not text:
        return None
    return Path(text).resolve()


def require_clean_git_tree(root: Path | None = None) -> None:
    base = root or package_root()
    porcelain = _git_porcelain(base)
    if porcelain.strip():
        raise ValueError(
            "dirty working tree; refuse non-SMOKE run from a git checkout. "
            "Commit or restore local changes.\n" + porcelain
        )


def require_runtime_integrity(*, is_smoke: bool, root: Path | None = None) -> str | None:
    if is_smoke:
        return None
    base = (root or package_root()).resolve()
    build = load_build_info_from_root(base)
    packaged = is_packaged_build_info(build)
    manifest_path = base / PACKAGE_MANIFEST_NAME
    if packaged and not manifest_path.is_file():
        raise ValueError(
            "PACKAGE_MANIFEST is required when _build_info.py is a packaged "
            "build; refusing git fallback"
        )
    if manifest_path.is_file():
        recomputed = verify_package_files(base)
        expected = str(build.get("package_content_hash") or "")
        if expected and expected != recomputed:
            raise ValueError(
                "PACKAGE_MANIFEST content_hash does not match _build_info "
                "PACKAGE_CONTENT_HASH; refuse tampered manifest"
            )
        return recomputed
    toplevel = _git_toplevel(base)
    if toplevel is None:
        raise ValueError(
            "no PACKAGE_MANIFEST and not a git checkout; "
            "refuse non-SMOKE run"
        )
    if toplevel != base:
        raise ValueError(
            f"git toplevel {toplevel} does not match package root {base}; "
            "refuse non-SMOKE run"
        )
    require_clean_git_tree(base)
    return None


def get_version_info() -> VersionInfo:
    """获取完整版本信息。打包部署优先 _build_info，避免 git rev-parse。"""
    build = _load_build_info()
    packaged = load_package_manifest()
    if packaged and build.get("commit"):
        return VersionInfo(
            version=build.get("version") or __version__,
            commit=build["commit"],
            branch=build.get("branch") or "unknown",
            dirty=bool(build.get("dirty", False)),
        )
    commit, branch, dirty = get_git_info()
    version = __version__
    if commit == "unknown" and build.get("commit"):
        commit = build["commit"]
        branch = build.get("branch") or branch
        dirty = bool(build.get("dirty", False))
        if build.get("version"):
            version = build["version"]

    return VersionInfo(
        version=version,
        commit=commit,
        branch=branch,
        dirty=dirty,
    )
