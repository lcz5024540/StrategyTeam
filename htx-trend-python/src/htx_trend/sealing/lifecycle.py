"""Independent upload and approval-bound release of sealed, unreferenced members."""
from contextlib import closing
import json
from pathlib import Path
import sqlite3
import tempfile

from .control import Control, SealingError, NeedsRestore, encoded, digest_file, lease, safe_file, stamp
from ..archive.transfer import archive, compact_staging, open_catalogue, restore, sync_directory
from ..archive.retirement import approved_plan
from ..archive.backend import digest


def source_spec(control, epoch):
    return {'kind': 'sealed-' + control.config['kind'], 'root': str(control.root), 'epoch': int(epoch)}


def virtual_path(control, path):
    return path if control.config['kind'] == 'cas' else 'segments/' + path


def archive_sealed(backend, root, work, *, min_free=5*1024**3, max_generations=4):
    control = Control(root)
    try:
        receipts = []
        from ..archive.scheduler import Scheduler
        cleaner = Scheduler(backend, work, {}, min_free=min_free)
        group = 'sealed-' + digest(encoded({'namespace': backend.identity, 'root': str(control.root)}))[:16] + '-'
        # Resume cleanup only for confirmed jobs generated by this exact source/namespace.
        for path in Path(work).glob(group + '*'):
            if not path.name[len(group):].isdigit():
                continue
            ack = control.db.execute('SELECT state FROM generations WHERE id=?', (int(path.name[len(group):]),)).fetchone()
            if ack and ack[0] in {'COS_VERIFIED','RETIRED'} and (path / 'receipt.json').exists():
                cleaner._release_job(path.name)
        for epoch, state, _, _ in list(control.db.execute("SELECT * FROM generations WHERE state='SEALED' ORDER BY id LIMIT ?", (max_generations,))):
            spec = source_spec(control, epoch)
            job = group + str(epoch)
            receipt = archive(backend, work, job, spec, min_free=min_free)
            with control.lease(), open_catalogue(backend, receipt['manifest'], work, min_free) as (manifest, catalogue):
                if manifest['source'] != spec:
                    raise SealingError('sealed archive source mismatch')
                rows = control.generation_rows(epoch)
                for row in rows:
                    remote = catalogue.execute('SELECT raw_hash,raw_size FROM files WHERE path=?',
                                               (virtual_path(control, row['path']),)).fetchone()
                    if remote is None or tuple(remote) != (row['raw_hash'], row['size']):
                        raise SealingError('sealed archive member mismatch')
                with control.guard, control.db:
                    control.db.execute("UPDATE generations SET state='COS_VERIFIED',manifest=? WHERE id=? AND state='SEALED'",
                                       (receipt['manifest'], epoch))
                    control.db.execute("UPDATE state SET value=value+1 WHERE name='revision'")
            compact_staging(backend, work, job)
            cleaner._release_job(job)
            receipts.append({'epoch': epoch, 'manifest': receipt['manifest'], 'files': receipt['files']})
        return {'status': 'VERIFIED' if receipts else 'NO_SEALED_GENERATIONS', 'receipts': receipts,
                'source_deleted': False, 'pending_generations': control.db.execute("SELECT count(*) FROM generations WHERE state='SEALED'").fetchone()[0]}
    finally:
        control.close()


def preview_release(backend, root, epoch, output, *, work, min_free=5*1024**3):
    control = Control(root)
    output = Path(output).absolute()
    if output.exists() or output.is_relative_to(control.root):
        control.close()
        raise SealingError('new release plan must be outside source')
    output.parent.mkdir(parents=True, exist_ok=True)
    try:
        with control.lease():
            row = control.db.execute('SELECT state,manifest FROM generations WHERE id=?', (epoch,)).fetchone()
            if not row or row[0] not in {'COS_VERIFIED', 'RETIRED'} or not row[1]:
                raise SealingError('generation lacks verified COS acknowledgement')
            manifest_key = row[1]
            revision, pinned = control.pin_snapshot()
            with open_catalogue(backend, manifest_key, work, min_free) as (manifest, catalogue):
                if manifest['source'] != source_spec(control, epoch):
                    raise SealingError('manifest belongs to another generation')
                with closing(sqlite3.connect(output)) as plan:
                    plan.executescript('''CREATE TABLE meta(name TEXT PRIMARY KEY,value TEXT);
                        CREATE TABLE files(path TEXT PRIMARY KEY,key TEXT,hash TEXT,size INTEGER,stamp TEXT,blocked TEXT);''')
                    plan.executemany('INSERT INTO meta VALUES(?,?)', [(k,encoded(v).decode()) for k,v in {
                        'schema': 'htx-segment-release-v1','namespace':backend.identity,'root':str(control.root),
                        'epoch':epoch,'manifest':manifest_key,'config':control.config,'revision':revision}.items()])
                    for path,key,raw_hash,size,local in control.db.execute('SELECT o.path,o.key,o.raw_hash,o.size,o.local FROM objects o JOIN members m ON o.path=m.path WHERE m.generation=? ORDER BY o.path',(epoch,)):
                        remote = catalogue.execute('SELECT raw_hash,raw_size FROM files WHERE path=?', (virtual_path(control,path),)).fetchone()
                        reason, fingerprint = None, None
                        if remote is None or tuple(remote) != (raw_hash,size):
                            reason = 'not-in-verified-manifest'
                        elif not local:
                            reason = 'already-released'
                        elif key in pinned:
                            reason = 'local-reference-pin'
                        else:
                            p = safe_file(control.root,path)
                            fingerprint = stamp(p)
                            if digest_file(p) != raw_hash or stamp(p) != fingerprint:
                                raise SealingError('member changed during release preview')
                        plan.execute('INSERT INTO files VALUES(?,?,?,?,?,?)',(path,key,raw_hash,size,fingerprint,reason))
                    plan.commit()
                    counts = dict(plan.execute("SELECT coalesce(blocked,'eligible'),count(*) FROM files GROUP BY blocked"))
                    size = plan.execute('SELECT coalesce(sum(size),0) FROM files WHERE blocked IS NULL').fetchone()[0]
            return {'plan':str(output),'approval_sha256':digest_file(output),'counts':counts,'eligible_bytes':size,
                    'manifest':manifest_key,'source_deleted':False}
    finally:
        control.close()


def apply_release(backend, plan_path, approval, *, work, min_free=5*1024**3, max_files=2000):
    if max_files < 1:
        raise SealingError('positive release batch limit required')
    work = Path(work)
    work.mkdir(parents=True,exist_ok=True)
    with approved_plan(plan_path,approval,work) as plan:
        meta = {r[0]:json.loads(r[1]) for r in plan.execute('SELECT name,value FROM meta')}
        if meta['schema'] != 'htx-segment-release-v1' or meta['namespace'] != backend.identity:
            raise SealingError('release plan schema/namespace mismatch')
        control = Control(meta['root'])
        try:
            if control.config != meta['config']:
                raise SealingError('source contract changed after preview')
            epoch = meta['epoch']
            row = control.db.execute('SELECT state,manifest FROM generations WHERE id=?',(epoch,)).fetchone()
            if not row or row[0] not in {'COS_VERIFIED','RETIRED'} or row[1] != meta['manifest']:
                raise SealingError('generation acknowledgement changed')
            with open_catalogue(backend,meta['manifest'],work,min_free) as (manifest,catalogue):
                if manifest['source'] != source_spec(control,epoch):
                    raise SealingError('release manifest source mismatch')
                for row in plan.execute('SELECT * FROM files WHERE blocked IS NULL'):
                    remote = catalogue.execute('SELECT raw_hash,raw_size FROM files WHERE path=?',(virtual_path(control,row['path']),)).fetchone()
                    member = control.db.execute('SELECT 1 FROM members WHERE generation=? AND path=?',(epoch,row['path'])).fetchone()
                    if remote is None or tuple(remote) != (row['hash'],row['size']) or not member:
                        raise SealingError('approved member is not in this sealed archive')
            with tempfile.TemporaryDirectory(prefix='sealed-verify-',dir=work) as temp:
                restore(backend,meta['manifest'],temp,scratch=work,all_files=True,verify_only=True,min_free=min_free)
            with control.lease():
                revision,pinned = control.pin_snapshot()
                candidates = []
                for row in plan.execute('SELECT * FROM files WHERE blocked IS NULL ORDER BY path'):
                    obj = control.db.execute('SELECT local,key,raw_hash FROM objects WHERE path=?',(row['path'],)).fetchone()
                    prior = control.db.execute('SELECT hash,stamp,state FROM deletes WHERE plan=? AND path=?',(approval,row['path'])).fetchone()
                    if not obj or tuple(obj[1:]) != (row['key'],row['hash']):
                        raise SealingError('approved member identity changed')
                    p = control.root / row['path']
                    if not p.exists() and prior and tuple(prior[:2]) == (row['hash'],row['stamp']):
                        if obj[0] == 0 and prior[2] == 'DONE':
                            continue
                        candidates.append((dict(row),False))
                        continue
                    if not obj[0] or row['key'] in pinned:
                        continue
                    p = safe_file(control.root,row['path'])
                    if stamp(p) != row['stamp'] or digest_file(p) != row['hash']:
                        raise SealingError('source differs from approved release list')
                    candidates.append((dict(row),True))
                    if len(candidates) >= max_files:
                        break
            released,removed = 0,0
            # One short EX lease per <=64 entries. COS/hash traversal is outside it.
            for offset in range(0,len(candidates),64):
                with lease(control.root,exclusive=True,blocking=False), control.guard:
                    control._require_handoff()
                    if control.db.execute("SELECT value FROM state WHERE name='revision'").fetchone()[0] != revision:
                        break  # A writer/pin changed; return partial progress and require a fresh reachability pass.
                    for row,exists in candidates[offset:offset+64]:
                        p = control.root / row['path']
                        if not exists and p.exists():
                            raise SealingError('member recreated after interrupted deletion; new preview required')
                        if exists:
                            safe_file(control.root,row['path'])
                            if stamp(p) != row['stamp']:
                                raise SealingError('member changed at release handoff')
                            with control.db:
                                control.db.execute('INSERT OR REPLACE INTO deletes VALUES(?,?,?,?,?)',
                                    (approval,row['path'],row['hash'],row['stamp'],'INTENT'))
                            p.unlink()
                            sync_directory(p.parent)
                            released += row['size']
                        with control.db:
                            control.db.execute('UPDATE objects SET local=0 WHERE path=?',(row['path'],))
                            control.db.execute("UPDATE state SET value=value+1 WHERE name='layout_revision'")
                            control.db.execute('INSERT OR REPLACE INTO deletes VALUES(?,?,?,?,?)',
                                (approval,row['path'],row['hash'],row['stamp'],'DONE'))
                            control.db.execute("UPDATE state SET value=value+1 WHERE name='revision'")
                        revision += 1
                        removed += 1
            with control.lease(),control.guard,control.db:
                remaining = control.db.execute('SELECT count(*) FROM members m JOIN objects o ON o.path=m.path WHERE m.generation=? AND o.local=1',(epoch,)).fetchone()[0]
                if remaining == 0:
                    control.db.execute("UPDATE generations SET state='RETIRED' WHERE id=?",(epoch,))
            return {'status':'RETIRED' if remaining == 0 else 'RETAINED_OR_PARTIAL','epoch':epoch,
                    'released_bytes':released,'removed_this_run':removed,'remaining_local_members':remaining,
                    'manifest':meta['manifest'],'approval_sha256':approval}
        finally:
            control.close()


def restore_local(backend, root, *, work, min_free=5*1024**3, max_files=2000):
    """Rehydrate exact cold members into the original layout; never replace the ledger/index."""
    from ..archive.transfer import free_guard
    import os
    work = Path(work).absolute()
    work.mkdir(parents=True, exist_ok=True)
    control = Control(root)
    try:
        if work.is_relative_to(control.root) or control.root.is_relative_to(work):
            raise SealingError('restoration scratch and source must be disjoint')
        if max_files < 1:
            raise SealingError('positive restoration limit required')
        with control.lease():
            rows = list(control.db.execute("SELECT path,raw_hash,size FROM objects o WHERE local=0 OR EXISTS (SELECT 1 FROM deletes d WHERE d.path=o.path AND d.state='INTENT') ORDER BY path LIMIT ?", (max_files,)))
        groups = {}
        with control.lease():
            for path,raw_hash,size in rows:
                ack = control.db.execute("SELECT g.id,g.manifest FROM members m JOIN generations g ON g.id=m.generation WHERE m.path=? AND g.state IN ('COS_VERIFIED','RETIRED') AND g.manifest IS NOT NULL ORDER BY g.id DESC LIMIT 1", (path,)).fetchone()
                if not ack:
                    raise NeedsRestore('cold member has no verified archive locator')
                groups.setdefault(ack,[]).append((path,raw_hash,size))
        restored = 0
        for (epoch,manifest_key), members in groups.items():
            with open_catalogue(backend,manifest_key,work,min_free) as (manifest,catalogue):
                if manifest['source'] != source_spec(control,epoch):
                    raise SealingError('restore locator source mismatch')
                for path,raw_hash,size in members:
                    remote = catalogue.execute('SELECT raw_hash,raw_size FROM files WHERE path=?',(virtual_path(control,path),)).fetchone()
                    if remote is None or tuple(remote) != (raw_hash,size):
                        raise SealingError('restore locator identity mismatch')
            with tempfile.TemporaryDirectory(prefix='rehydrate-',dir=work) as temp:
                restore(backend,manifest_key,temp,scratch=work,paths=[virtual_path(control,r[0]) for r in members],min_free=min_free)
                for path,raw_hash,size in members:
                    virtual = virtual_path(control,path)
                    source = Path(temp) / virtual
                    if digest_file(source) != raw_hash:
                        raise SealingError('restore hash mismatch')
                    # Network and hashing finished. Atomic publication only under the local EX lease.
                    with lease(control.root,exclusive=True,blocking=False), control.guard:
                        obj = control.db.execute('SELECT local,raw_hash FROM objects WHERE path=?', (path,)).fetchone()
                        if obj[0] and (control.root/path).exists():
                            continue  # Writer already regenerated it; never overwrite new local bytes.
                        if obj[1] != raw_hash:
                            raise SealingError('cold member identity changed during restoration')
                        target = control.root / path
                        for part in (target,*target.parents):
                            if part.is_symlink():
                                raise SealingError('symlink rehydration path')
                            if part == control.root:
                                break
                        target.parent.mkdir(parents=True,exist_ok=True)
                        free_guard(control.root,min_free,size)
                        if target.exists():
                            if digest_file(target) != raw_hash:
                                raise SealingError('restoration conflicts with existing untracked bytes')
                        else:
                            # Scratch may be on another device; publish through a local temporary file.
                            import shutil
                            with tempfile.NamedTemporaryFile(dir=target.parent,prefix='.rehydrate-',delete=False) as f:
                                temporary = Path(f.name)
                                try:
                                    with source.open('rb') as src:
                                        shutil.copyfileobj(src,f)
                                    f.flush()
                                    os.fsync(f.fileno())
                                    os.link(temporary,target)
                                finally:
                                    temporary.unlink()
                            sync_directory(target.parent)
                        with control.db:
                            control.db.execute('UPDATE objects SET local=1 WHERE path=?',(path,))
                            control.db.execute("UPDATE state SET value=value+1 WHERE name='layout_revision'")
                            control.db.execute("UPDATE deletes SET state='RECOVERED' WHERE path=? AND state='INTENT'",(path,))
                            control.db.execute("UPDATE state SET value=value+1 WHERE name='revision'")
                        restored += 1
        return {'status':'RESTORED' if rows else 'ALL_LOCAL','restored':restored,
                'remaining_cold':control.db.execute('SELECT count(*) FROM objects WHERE local=0').fetchone()[0],
                'global_index_replaced':False}
    finally:
        control.close()


def rollback_layout(root, *, writer_stopped=False):
    """Offline verification and capture index materialization for a previous package."""
    if not writer_stopped:
        raise SealingError('rollback verification requires stopped-writer acknowledgement')
    from ..archive.transfer import atomic
    control = Control(root)
    try:
        with lease(control.root,exclusive=True,blocking=False):
            if control.db.execute('SELECT 1 FROM mutations').fetchone() or (control.directory/'BLOCK_RELEASE').exists():
                raise SealingError('offline reconciliation required before rollback')
            for path,raw_hash,local in control.db.execute('SELECT path,raw_hash,local FROM objects'):
                if not local or digest_file(safe_file(control.root,path)) != raw_hash:
                    raise NeedsRestore('complete local restoration required before rollback')
            if control.config['kind']=='capture':
                # Global legacy index is intentionally rebuilt only with writers stopped.
                records = [json.loads(r[0]) for r in control.db.execute('SELECT metadata FROM objects ORDER BY rowid')]
                records.sort(key=lambda r:(r.get('first_received_ms') or 0,r['hash']))
                atomic(control.root/'segments.jsonl',b''.join(encoded(r)+b'\n' for r in records))
            else:
                from ..research.store import _read_object
                with closing(sqlite3.connect((control.root/'index.sqlite3').as_uri()+'?mode=ro',uri=True)) as index:
                    for key, in index.execute('SELECT hash FROM evidence'):
                        _read_object(control.root,key)
                for child, in control.db.execute('SELECT DISTINCT child FROM edges'):
                    _read_object(control.root,child)
            return {'status':'LEGACY_LAYOUT_VERIFIED','root':str(control.root),'ledger_changed':False,
                    'note':'All payloads local; sealing metadata retained. Previous package may read legacy layout. Do not run it concurrently with segment maintenance.'}
    finally:
        control.close()
